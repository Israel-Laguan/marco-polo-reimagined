#!/usr/bin/env python3
"""Give each chapter Note a Yule chapter locator where the body passage matches clearly (APP.T5).

usage: python3 tools/yc_note_locate.py [--apply] [--worklist FILE]   (run from book/)

For each Note in a narrative chapter with no `[@yc, …]`, take the body paragraph carrying its
[n], and count the 5-grams it shares with each Yule chapter's main text. A clear match (at
least MIN shared 5-grams, at least RATIO times the runner-up, inside the Yule range the
chapter covers) puts `[@yc, b.c]` after the Note's opening marker. Weak, missing and
out-of-range cases go to the worklist, not into the text. Without --apply it is a dry run.
"""
import argparse
import re
import sys
from functools import lru_cache
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import yule  # noqa: E402
import cite_convert as cc  # noqa: E402
import cite_locate as cl  # noqa: E402

from paths import EDITORIAL

BOOK = yule.BOOK
MIN, RATIO = 8, 2
NOTE = re.compile(r"^\[(\d+)\] ((?:[✓~✗◇?])(?:\s*/\s*[✓~✗◇?])?)(\s)", re.M)


@lru_cache(maxsize=None)
def chapter_grams():
    return [(b, c, set(yule.grams(text.split(), 5))) for b, c, text, _ in cc.chapters()]


def locator(b, c):
    return f"[@yc, Prol. {c}]" if b == 0 else f"[@yc, {b}.{c}]"


def classify(para, allowed):
    """(verdict, (book, chapter) or None, best, runner-up) for one body paragraph."""
    g = set(yule.grams(yule.norm(re.sub(r"\[\d+\]", " ", para)), 5))
    scores = sorted(((len(g & cg), b, c) for b, c, cg in chapter_grams()), reverse=True)
    (best, b, c), (second, _, _) = scores[0], scores[1]
    if best < MIN:
        return "no match", None, best, second
    if best < RATIO * second:
        return "weak", (b, c), best, second
    if (b, c) not in allowed or (b, c) == (0, 0):
        return "out of range", (b, c), best, second
    return "clear", (b, c), best, second


def run(paths, apply):
    rows = []
    for path in paths:
        cid = cl.chapter_id(path)
        allowed = set(cl.ranges().get(cid, []))
        text = path.read_text(encoding="utf-8")
        i = text.index("\n## Notes")
        body, notes = text[:i], text[i:]
        paras = [p for p in body.split("\n\n")]
        def place(m):
            n = int(m.group(1))
            line = notes[m.start():notes.find("\n", m.start())]
            if "@yc" in line:
                return m.group(0)
            para = next((p for p in paras if re.search(r"\[%d\](?!\()" % n, p)), None)
            if para is None:
                rows.append((path, n, "no anchor", None, 0, 0)); return m.group(0)
            verdict, bc, best, second = classify(para, allowed)
            rows.append((path, n, verdict, bc, best, second))
            return f"[{n}] {m.group(2)} {locator(*bc)}{m.group(3)}" if verdict == "clear" else m.group(0)
        new = NOTE.sub(place, notes)
        if apply and new != notes:
            path.write_text(body + new, encoding="utf-8")
    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--worklist", default=EDITORIAL / "plans/status/yc-locator-worklist.md")
    a = ap.parse_args()
    paths = sorted(p for p in BOOK.glob("vol-*/ch-*.md") if cl.chapter_id(p) in cl.ranges())
    rows = run(paths, a.apply)
    counts = {}
    for r in rows:
        counts[r[2]] = counts.get(r[2], 0) + 1
    print(counts)
    out = ["# Yule locator worklist (APP.T5)", "",
           f"Generated by `tools/yc_note_locate.py`. Rule: ≥ {MIN} shared 5-grams, ≥ {RATIO}× the runner-up, "
           "inside the chapter's Yule range. Clear matches were placed; the rest need a person.", "",
           "| Note | Verdict | Best Yule chapter | Shared / runner-up |", "|---|---|---|---|"]
    for path, n, verdict, bc, best, second in rows:
        if verdict != "clear":
            where = locator(*bc) if bc else "—"
            out.append(f"| {path.relative_to(BOOK)} [{n}] | {verdict} | {where} | {best} / {second} |")
    out.append("")
    out.append(f"Totals: {counts}.")
    Path(a.worklist).write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
